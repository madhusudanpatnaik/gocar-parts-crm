function loadCart() {
  fetch("fetch-cart.php?action=fetch", {
    credentials: "include"
  })
    .then(res => {
      if (!res.ok) throw new Error("Network response was not ok");
      return res.json();
    })
    .then(data => {
      const tbody = document.getElementById("cart-body");
      tbody.innerHTML = "";

      let grandTotal = 0;

      data.forEach(item => {
        const price = parseFloat(item.price);
        const total = price * item.quantity;
        grandTotal += total;

        const row = document.createElement("tr");
        row.className = "cart__table--body__items";
        row.innerHTML = `
          <td class="cart__table--body__list">
            <div class="cart__product d-flex align-items-center">
              <button class="cart__remove--btn" onclick="deleteCartItem(${item.cart_id})">
                <svg fill="currentColor" xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" width="16px" height="16px">
                  <path d="M4.7 3.3L3.3 4.7 10.6 12 3.3 19.3 4.7 20.7 12 13.4 19.3 20.7 20.7 19.3 13.4 12 20.7 4.7 19.3 3.3 12 10.6z"/>
                </svg>
              </button>
              <div class="cart__thumbnail">
                <img class="border-radius-5" src="${item.image}" alt="cart-product">
              </div>
              <div class="cart__content">
                <h3 class="cart__content--title h4">${item.title}</h3>
              </div>
            </div>
          </td>
          <td class="cart__table--body__list">
            <span class="cart__price">$${price.toFixed(2)}</span>
          </td>
          <td class="cart__table--body__list">
            <div class="quantity__box">
              <button type="button" class="quantity__value decrease" onclick="updateQuantity(${item.cart_id}, ${item.quantity - 1})">-</button>
              <input type="number" class="quantity__number" value="${item.quantity}" onchange="updateQuantity(${item.cart_id}, this.value)">
              <button type="button" class="quantity__value increase" onclick="updateQuantity(${item.cart_id}, ${item.quantity + 1})">+</button>
            </div>
          </td>
          <td class="cart__table--body__list">
            <span class="cart__price end">$${total.toFixed(2)}</span>
          </td>
        `;
        tbody.appendChild(row);
      });

      document.querySelectorAll(".cart__summary--amount").forEach(el => {
        el.textContent = `$${grandTotal.toFixed(2)}`;
      });
    })
    .catch(err => {
      console.error("Failed to load cart:", err);
      document.getElementById("cart-body").innerHTML = `<tr><td colspan="4" style ="color:red"><h2>Please Login, Failed to load cart</h2></td></tr>`;
    });
}

function updateQuantity(cartId, qty) {
  qty = parseInt(qty);
  if (qty < 1) return;

  fetch("fetch-cart.php?action=update", {
    method: "POST",
    headers: { "Content-Type": "application/x-www-form-urlencoded" },
    body: `cart_id=${cartId}&quantity=${qty}`
  })
    .then(res => res.text())
    .then(() => loadCart())
    .catch(err => console.error("Update failed:", err));
}

function deleteCartItem(cartId) {
  fetch("fetch-cart.php?action=delete", {
    method: "POST",
    headers: { "Content-Type": "application/x-www-form-urlencoded" },
    body: `cart_id=${cartId}`
  })
    .then(res => res.text())
    .then(() => loadCart())
    .catch(err => console.error("Delete failed:", err));
}


